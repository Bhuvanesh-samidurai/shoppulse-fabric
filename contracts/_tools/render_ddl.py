"""Render the DDL notebooks from contracts/ and sql/ (owner: DE2).

    python contracts/_tools/render_ddl.py          # write fabric/data/nb_ddl_*.Notebook
    python contracts/_tools/render_ddl.py --check  # exit 1 if the committed notebooks are stale

The notebooks are generated, never edited by hand, so a contract and its DDL cannot drift.
CD runs them in name order after every deploy (infra/ci/run_notebooks.py --pattern "nb_ddl_*"):

    nb_ddl_10_sqldb   shop + wb schemas in sqldb_shop (sql/*.sql)
    nb_ddl_20_bronze  Bronze tables + shortcuts to the sqldb_shop mirror
    nb_ddl_30_silver  Silver + ops tables, static seeds (warehouse, carrier)
    nb_ddl_40_gold    Gold tables, unknown members (-1), dim_date, dim_time
"""
