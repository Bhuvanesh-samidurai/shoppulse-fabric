COMMON = r'''
# GENERATED by contracts/_tools/render_ddl.py from contracts/ - DO NOT EDIT BY HAND.
import datetime as dt
import json

import notebookutils
import requests
from delta.tables import DeltaTable


def utcnow():
    return dt.datetime.now(dt.UTC).replace(tzinfo=None)  # naive UTC, matches Spark timestamp


RUN_ID = "ddl-" + utcnow().strftime("%Y%m%dT%H%M%S")
WS_ID = notebookutils.runtime.context["currentWorkspaceId"]
FABRIC_API = "https://api.fabric.microsoft.com/v1"
changes = []


def fabric(method, path, body=None):
    h = {"Authorization": "Bearer " + notebookutils.credentials.getToken("pbi")}
    r = requests.request(method, f"{FABRIC_API}/{path}", headers=h, json=body, timeout=60)
    if not r.ok:
        raise RuntimeError(f"{method} {path}: {r.status_code} {r.text[:300]}")
    return r.json() if r.content else {}


def item_id(name, item_type):
    for it in fabric("GET", f"workspaces/{WS_ID}/items?type={item_type}")["value"]:
        if it["displayName"] == name:
            return it["id"]
    raise RuntimeError(f"{item_type} {name} not found in workspace {WS_ID}; deploy fabric/data first")


_lh = {}


def table_path(spec):
    lh = spec["lakehouse"]
    if lh not in _lh:
        _lh[lh] = item_id(lh, "Lakehouse")
    return f"abfss://{WS_ID}@onelake.dfs.fabric.microsoft.com/{_lh[lh]}/Tables/{spec['schema']}/{spec['name']}"


def ensure_table(spec):
    """Create or evolve one Delta table to match its contract. Never drops anything."""
    path = table_path(spec)
    q = f"delta.`{path}`"
    cols = spec["columns"]
    if not DeltaTable.isDeltaTable(spark, path):
        col_sql = ", ".join(f"`{n}` {t}{'' if nullable else ' NOT NULL'}" for n, t, nullable in cols)
        part = f" PARTITIONED BY ({', '.join(spec['partition_by'])})" if spec["partition_by"] else ""
        props = dict(spec["properties"], **{"shoppulse.contract_version": spec["version"]})
        prop_sql = ", ".join(f"'{k}' = '{v}'" for k, v in props.items())
        spark.sql(f"CREATE TABLE IF NOT EXISTS {q} ({col_sql}) USING DELTA{part} TBLPROPERTIES ({prop_sql})")
        changes.append(f"created {spec['table']}")
    else:
        existing = {f.name for f in spark.read.format("delta").load(path).schema}
        missing = [(n, t, nl) for n, t, nl in cols if n not in existing]
        if any(not nl for _, _, nl in missing):
            raise RuntimeError(f"{spec['table']}: new NOT NULL columns need a migration: {missing}")
        if missing:
            spark.sql(f"ALTER TABLE {q} ADD COLUMNS ({', '.join(f'`{n}` {t}' for n, t, _ in missing)})")
            changes.append(f"{spec['table']}: added {[m[0] for m in missing]}")
        current = spark.sql(f"DESCRIBE DETAIL {q}").first()["properties"]
        want = dict(spec["properties"], **{"shoppulse.contract_version": spec["version"]})
        diff = {k: v for k, v in want.items() if current.get(k) != v}
        if diff:
            spark.sql(f"ALTER TABLE {q} SET TBLPROPERTIES ({', '.join(f'{chr(39)}{k}{chr(39)} = {chr(39)}{v}{chr(39)}' for k, v in diff.items())})")
            changes.append(f"{spec['table']}: properties {sorted(diff)}")
    current = spark.sql(f"DESCRIBE DETAIL {q}").first()["properties"]
    for name, expr in spec["constraints"].items():
        if f"delta.constraints.{name.lower()}" not in current:
            spark.sql(f"ALTER TABLE {q} ADD CONSTRAINT {name} CHECK ({expr})")
            changes.append(f"{spec['table']}: constraint {name}")
    return path


def append_rows(spec, rows, only_if_empty=False, key=None):
    """Insert seed rows. only_if_empty: skip when the table has any row except key -1."""
    path = table_path(spec)
    df = spark.read.format("delta").load(path)
    if only_if_empty:
        existing = df.filter(f"{key} <> -1") if key else df
        if existing.limit(1).count():
            return
    if not rows:
        return
    names = [f.name for f in df.schema]
    spark.createDataFrame([tuple(r.get(n) for n in names) for r in rows], df.schema).write.format("delta").mode("append").save(path)
    changes.append(f"{spec['table']}: seeded {len(rows)} rows")


def finish():
    print(json.dumps({"run_id": RUN_ID, "changes": changes or ["no changes"]}, indent=1))
'''

UNKNOWN = r'''
DEFAULTS = {"string": "unknown", "int": -1, "bigint": -1, "tinyint": -1, "double": None, "boolean": False,
            "date": dt.date(1900, 1, 1), "timestamp": dt.datetime(1900, 1, 1)}


def unknown_row(spec):
    from decimal import Decimal
    row = {}
    for n, t, nullable in spec["columns"]:
        v = Decimal(0) if t.startswith("decimal") else DEFAULTS[t]
        if v is None and not nullable:
            v = 0.0
        row[n] = v
    row.update({k: -1 for k in spec["primary_key"]})
    if spec["scd"] == "2":
        row.update(valid_to=dt.datetime(9999, 12, 31), is_current=True, row_hash="unknown")
    row.update(_updated_at=dt.datetime(1900, 1, 1), _run_id="seed")
    return row


def ensure_unknown_member(spec):
    path = table_path(spec)
    pk = spec["primary_key"][0]
    if spark.read.format("delta").load(path).filter(f"{pk} = -1").limit(1).count() == 0:
        append_rows(spec, [unknown_row(spec)])
'''

CALENDAR = r'''
def easter(y):
    a, b, c = y % 19, y // 100, y % 100
    d, e = b // 4, b % 4
    g = (8 * b + 13) // 25
    h = (19 * a + b - d - g + 15) % 30
    j, k = c // 4, c % 4
    m = (a + 11 * h) // 319
    r = (2 * e + 2 * j - k - h + m + 32) % 7
    n = (h - m + r + 90) // 25
    return dt.date(y, n, (h - m + r + n + 19) % 32)


def national_holidays(y):
    e = easter(y)
    return {dt.date(y, 1, 1): "Neujahr", e - dt.timedelta(2): "Karfreitag", e + dt.timedelta(1): "Ostermontag",
            dt.date(y, 5, 1): "Tag der Arbeit", e + dt.timedelta(39): "Christi Himmelfahrt", e + dt.timedelta(50): "Pfingstmontag",
            dt.date(y, 10, 3): "Tag der Deutschen Einheit", dt.date(y, 12, 25): "1. Weihnachtstag", dt.date(y, 12, 26): "2. Weihnachtstag"}


def black_friday(y):
    d = dt.date(y, 11, 1)
    first_thu = d + dt.timedelta((3 - d.weekday()) % 7)
    return first_thu + dt.timedelta(22)


def dim_date_rows(start=dt.date(2016, 1, 1), end=dt.date(2030, 12, 31)):
    months = ["Januar", "Februar", "Maerz", "April", "Mai", "Juni", "Juli", "August", "September", "Oktober", "November", "Dezember"]
    days = ["Montag", "Dienstag", "Mittwoch", "Donnerstag", "Freitag", "Samstag", "Sonntag"]
    hol, rows, d = {}, [], start
    for y in range(start.year, end.year + 1):
        hol.update(national_holidays(y))
    while d <= end:
        bf = black_friday(d.year)
        bf_monday = bf - dt.timedelta(bf.weekday())
        rows.append({"date_key": int(d.strftime("%Y%m%d")), "date": d, "year": d.year, "quarter": (d.month - 1) // 3 + 1, "month": d.month,
                     "month_name": months[d.month - 1], "iso_week": d.isocalendar()[1], "day_of_week": d.isoweekday(), "day_name": days[d.weekday()],
                     "is_weekend": d.weekday() >= 5, "is_holiday_de": d in hol, "holiday_name": hol.get(d),
                     "is_black_friday_week": bf_monday <= d <= bf + dt.timedelta(3), "is_q4_peak": bf <= d <= dt.date(d.year, 12, 24),
                     "_updated_at": utcnow(), "_run_id": RUN_ID})
        d += dt.timedelta(1)
    return rows


def dim_time_rows():
    def part(h):
        return "night" if h < 6 else "morning" if h < 12 else "afternoon" if h < 18 else "evening"
    return [{"time_key": h * 100 + m, "hour": h, "minute": m, "day_part": part(h), "_updated_at": utcnow(), "_run_id": RUN_ID}
            for h in range(24) for m in range(60)]
'''

