NS = uuid.UUID("6d1c3f44-6a0b-4d55-9b8e-5f0d0a2c7e10")  # stable logicalIds per notebook name


def load_contracts() -> list[dict]:
    return [yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "contracts").rglob("*.yml"))]


def table_spec(d: dict) -> dict:
    layer, name = d["table"].split(".")
    return {
        "table": d["table"],
        "lakehouse": d["lakehouse"],
        "schema": "ops" if layer == "ops" else "dbo",
        "name": name,
        "version": d["version"],
        "columns": [[c["name"], c["type"], c["nullable"]] for c in d["columns"]],
        "partition_by": d["partition_by"],
        "properties": {k: str(v).lower() if isinstance(v, bool) else str(v) for k, v in d["delta_properties"].items()},
        "constraints": {x["name"]: x["check"] for x in d.get("constraints", [])},
        "primary_key": d["primary_key"],
        "scd": d["scd"],
        "unknown_member": bool(d.get("unknown_member")),
    }


def sql_batches() -> list[str]:
    batches = []
    for p in sorted((ROOT / "sql").glob("*.sql")):
        for b in re.split(r"^\s*GO\s*$", p.read_text(encoding="utf-8"), flags=re.MULTILINE):
            body = "\n".join(line for line in b.splitlines() if line.strip() and not line.strip().startswith("--")).strip()
            if body:
                batches.append(body)
    return batches


